#!/usr/bin/env bash
# Prints the Homebrew formula for a HubWatch release on stdout.
# Used by .github/workflows/release.yml to update the tap after a release.
#
# Usage: formula.sh <tag> <owner/repo> <dir with the osx zips> [download base URL]
#   e.g. formula.sh v0.3.0 andemt/hubwatch dist > Formula/hubwatch.rb
# The base URL defaults to the GitHub release; test-local.sh passes a file:// URL instead.
#
# The formula installs HubWatch.app (the menu bar app with the server inside it) and puts a `hubwatch` command for
# the server on the PATH. Files downloaded by brew get no quarantine attribute, so Gatekeeper does not block the
# ad-hoc signed app the way it does a download from the browser.
set -euo pipefail

tag="$1"
repo="$2"
dist="$3"
base="${4:-https://github.com/${repo}/releases/download/${tag}}"

sha() { shasum -a 256 "${dist}/HubWatch-${tag}-$1.zip" | cut -d' ' -f1; }
arm_sha=$(sha osx-arm64)
intel_sha=$(sha osx-x64)

cat <<EOF
# Generated by packaging/homebrew/formula.sh in ${repo}. Do not edit by hand: changes are overwritten on the next release.
class Hubwatch < Formula
  desc "Local real-time log of everything that happens in your Philips Hue system"
  homepage "https://github.com/${repo}"
  version "${tag#v}"
  license "MIT"

  depends_on :macos

  on_arm do
    url "${base}/HubWatch-${tag}-osx-arm64.zip"
    sha256 "${arm_sha}"
  end
  on_intel do
    url "${base}/HubWatch-${tag}-osx-x64.zip"
    sha256 "${intel_sha}"
  end

  def install
    # Homebrew changes into the archive's only folder, which here is HubWatch.app itself.
    if File.exist?("Contents/Info.plist")
      (prefix/"HubWatch.app").install Dir["*"]
    else
      prefix.install "HubWatch.app"
    end
    # The server alone, for the terminal and brew services. It finds wwwroot next to itself inside the app.
    # (write_exec_script would name the script after its target, HubWatch, so write the wrapper ourselves.)
    bin.mkpath
    (bin/"hubwatch").write <<~SH
      #!/bin/bash
      exec "#{opt_prefix}/HubWatch.app/Contents/Resources/server/HubWatch" "\$@"
    SH
    chmod 0755, bin/"hubwatch"
  end

  # After install, Homebrew rewrites the install name of the bundled SQLite library, which breaks the app's sealed
  # (ad-hoc) signature. Sign the app again once that has happened.
  def post_install
    system "codesign", "--force", "--sign", "-", prefix/"HubWatch.app"
  end

  # brew services start hubwatch: keep recording in the background, also after a restart.
  service do
    run [opt_bin/"hubwatch", "--no-browser"]
    keep_alive true
    log_path var/"log/hubwatch.log"
    error_log_path var/"log/hubwatch.log"
  end

  def caveats
    <<~TEXT
      To put HubWatch in your Applications folder (it stays up to date with brew upgrade):
        ln -sfn "#{opt_prefix}/HubWatch.app" /Applications/HubWatch.app
      Then open HubWatch like any other app. It keeps recording in the menu bar when you close its window.

      Or without the app: run "hubwatch" in a terminal (opens your browser at http://localhost:5080),
      or "brew services start hubwatch" to record in the background, also after a restart.

      Your data is stored in ~/Library/Application Support/HubWatch.
    TEXT
  end

  test do
    assert_predicate bin/"hubwatch", :file?
    assert_predicate bin/"hubwatch", :executable?
    assert_predicate prefix/"HubWatch.app/Contents/MacOS/HubWatch", :executable?
    assert_predicate prefix/"HubWatch.app/Contents/Resources/server/wwwroot/index.html", :exist?
  end
end
EOF
